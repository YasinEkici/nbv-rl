"""Fetch base parts, build the split manifest, and generate deviation variants.

    uv run python scripts/prepare_parts.py fetch    --config configs/parts_v1.yaml
    uv run python scripts/prepare_parts.py split    --config configs/parts_v1.yaml --out configs/split_v1.yaml
    uv run python scripts/prepare_parts.py variants --config configs/parts_v2.yaml --manifest configs/split_v1.yaml
"""

import argparse
import json
from pathlib import Path

from nbv import parts


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["fetch", "split", "variants"])
    ap.add_argument("--config", required=True)
    ap.add_argument("--out", default="configs/split_v1.yaml")
    ap.add_argument("--manifest", default="configs/split_v1.yaml")
    args = ap.parse_args()

    cfg = parts.load_yaml(args.config)
    raw = Path(cfg["paths"]["raw"])
    meta_path = raw / "metadata.yaml"

    if args.command == "fetch":
        ids = [p["file_id"] for p in cfg["parts"]]
        meta = parts.fetch_parts(ids, raw, cfg["paths"]["thingi10k_cache"])
        parts.write_yaml({"parts": meta}, meta_path)
        print(f"wrote {len(meta)} parts to {raw}")
    elif args.command == "split":
        meta = parts.load_yaml(meta_path)["parts"]
        manifest = parts.build_manifest(cfg, meta, Path(args.config).as_posix())
        header = f"# Generated by scripts/prepare_parts.py split from {args.config}. Do not edit.\n"
        parts.write_yaml(manifest, args.out, header=header)
        print(f"wrote {args.out}: {manifest['counts']}")
    else:
        manifest = parts.load_yaml(args.manifest)
        out = Path(cfg["paths"]["variants"])
        hashes = parts.generate_variants(cfg, manifest, raw, out)
        (out / "hashes.json").write_text(json.dumps(hashes, indent=1), encoding="utf-8")
        print(f"wrote {len(hashes)} variants to {out}")


if __name__ == "__main__":
    main()
